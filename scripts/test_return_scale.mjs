import { chromium } from 'playwright-core';
const browser = await chromium.launch({ executablePath: '/Applications/Google Chrome.app/Contents/MacOS/Google Chrome', headless: true, args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader'] });
const page = await browser.newPage({ viewport:{width:1200,height:760} });
const errs=[]; page.on('pageerror',e=>errs.push(e.message));
await page.goto('http://127.0.0.1:5173/?quality=low',{waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>window.EON?.catalogsReady,null,{timeout:90000}).catch(()=>{});
await page.waitForTimeout(5000);
await page.click('#search-input'); await page.fill('#search-input','TRAPPIST-1e'); await page.waitForTimeout(500); await page.keyboard.press('Enter');
await page.waitForFunction(()=>EON.domain==='exo',null,{timeout:60000});
await page.waitForTimeout(1000);
await page.click('#exo-return');
await page.waitForFunction(()=>EON.domain==='deep',null,{timeout:30000});
await page.waitForTimeout(300);
const before = await page.evaluate(()=>({ target:EON.deep.rig.targetDistance, dist:EON.deep.rig.distance, cap:document.querySelector('#scale-caption').textContent }));
await page.evaluate(()=>{ document.querySelector('.scale-stop[data-id="local-group"]').click(); });
await page.waitForTimeout(1500);
const after = await page.evaluate(()=>({ target:EON.deep.rig.targetDistance, dist:EON.deep.rig.distance, cap:document.querySelector('#scale-caption').textContent, focus:EON.deep.focusLevel }));
console.log({before,after,errs});
await browser.close();
