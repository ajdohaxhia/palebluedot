import { chromium } from 'playwright-core';
const browser=await chromium.launch({executablePath:'/Applications/Google Chrome.app/Contents/MacOS/Google Chrome',headless:true,args:['--no-sandbox','--use-angle=swiftshader','--enable-unsafe-swiftshader']});
const page=await browser.newPage({viewport:{width:1280,height:800}});
await page.goto('http://127.0.0.1:5173/?quality=low',{waitUntil:'domcontentloaded'});
await page.waitForFunction(()=>window.EON?.ready,null,{timeout:90000});
await page.evaluate(()=>localStorage.removeItem('cosmos.step'));
await page.waitForTimeout(600);
await page.click('[data-cs="start"]');
await page.waitForTimeout(1000);
await page.evaluate(()=>COSMOS.go(10)); // slide 11, Pioneer plaque
await page.waitForTimeout(1200);
await page.click('.cs-tool-cta');
await page.waitForTimeout(900);
await page.evaluate(()=>cancelAnimationFrame(window.EON.frameHandle));
await page.screenshot({path:'screenshots/cosmos-3d-drawer.png',timeout:60000,animations:'disabled'});
console.log('drawer shot');
await page.click('.cs-card-toggle');
await page.waitForTimeout(300);
await page.click('.cs-top-actions [data-cs="free-atlas"]');
await page.waitForTimeout(1200);
await page.evaluate(()=>cancelAnimationFrame(window.EON.frameHandle));
await page.screenshot({path:'screenshots/cosmos-free-atlas.png',timeout:60000,animations:'disabled'});
console.log('free shot');
await page.click('#cosmos-free-return');
await page.waitForTimeout(900);
await page.click('.cs-top-actions [data-cs="present"]');
await page.waitForTimeout(700);
await page.evaluate(()=>cancelAnimationFrame(window.EON.frameHandle));
await page.screenshot({path:'screenshots/cosmos-present-3d.png',timeout:60000,animations:'disabled'});
console.log('present shot');
process.exit(0);
